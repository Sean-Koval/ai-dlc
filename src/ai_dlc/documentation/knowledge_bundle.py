"""Merge-time steps for a knowledge repository: number records, then write indexes.

``number_records`` gives each record that still has a draft slug id the next
``DEC-``/``CONV-``/``LES-``/``ACT-``/``Q-``/``SRC-`` number for its type. The slug
moves to ``aliases``, a file named after the slug is renamed, and every typed link,
``sources`` entry and relative markdown link that pointed at the slug or its file is
rewritten. ``index_records`` writes one Open Knowledge Format v0.2 section 8
``index.md`` per directory; the root one carries ``okf_version: "0.2"``. Each index
also derives ``superseded_by`` and ``retracted_by`` (KAN-479), so records are never
edited to carry them; a retracted record is listed as retracted, not accepted. A
``boundary: customer`` record is listed and counted only by the indexes inside its
own ``projects/<name>/``; no other index lists it or links into that project.

Both are deterministic, use no model and change nothing on a second run. Both read
the directories in ``[check] roots`` of ``knowledge.toml`` (all of ``root`` when
unset). With ``write=False`` they only report what they would change. Numbering is
meant for CI on the default branch after a merge (the reusable workflow
``.github/workflows/knowledge-merge.yml``); CLI and MCP call these functions.
"""

import os
import re
import tomllib
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any

import yaml

from ai_dlc.documentation import knowledge_records as records
from ai_dlc.documentation.knowledge_check import is_customer, project_of, visible_in
from ai_dlc.documentation.knowledge_notes import split

CONFIG = "knowledge.toml"
INDEX = "index.md"
RESERVED = ("index.md", "log.md")
SKIPPED = ("README.md",)
OKF_VERSION = "0.2"
NUMBERED = re.compile(r"^(?:DEC|CONV|LES|ACT|Q|SRC)-([0-9]{4,})$")
INACTIVE = ("superseded", "rejected", records.RETRACTED)
HEADINGS = {
    "decision": "Decisions",
    "convention": "Conventions",
    "lesson": "Lessons",
    "action": "Actions",
    "question": "Questions",
    "source": "Sources",
}
GENERATED = "<!-- Generated by ai-dlc knowledge index; do not edit. -->"
# A relative markdown link target: ](target) with an optional #fragment.
MARKDOWN_LINK = re.compile(r"(\]\()([^)\s#]+)(#[^)\s]*)?(\))")


@dataclass(eq=False)
class _Record:
    path: Path
    relative: str
    text: str
    raw: str
    data: dict
    body: str
    record: records.KnowledgeRecord


class _Scan:
    def __init__(self, folder: Path) -> None:
        self.folder = folder
        self.records: list[_Record] = []
        self.failures: list[dict[str, str]] = []
        self.roots: list[Path] = []

    def fail(self, path: str, message: str) -> None:
        self.failures.append({"path": path, "message": message})


def _roots(scan: _Scan) -> None:
    config = scan.folder / CONFIG
    if not config.is_file():
        scan.roots = [scan.folder]
        return
    try:
        table = tomllib.loads(config.read_text(encoding="utf-8")).get("check")
    except (tomllib.TOMLDecodeError, UnicodeDecodeError) as exc:
        scan.fail(CONFIG, f"not valid TOML: {exc}")
        return
    names = table.get("roots") if isinstance(table, dict) else None
    if names is None:
        scan.roots = [scan.folder]
        return
    if not isinstance(names, list) or not all(isinstance(name, str) for name in names):
        scan.fail(CONFIG, "[check] roots must be a list of record directories")
        return
    for name in names:
        directory = (scan.folder / name).resolve()
        if not directory.is_relative_to(scan.folder) or not directory.is_dir():
            scan.fail(CONFIG, f"[check] roots: {name} is not a directory inside the records")
        else:
            scan.roots.append(directory)


def _markdown(folder: Path) -> list[Path]:
    found = []
    for path in sorted(folder.rglob("*.md")):
        parts = path.relative_to(folder).parts
        if any(part.startswith(".") for part in parts) or path.is_symlink():
            continue
        if path.is_file() and path.name not in RESERVED + SKIPPED:
            found.append(path)
    return found


def _scan(root: Path | str) -> _Scan:
    folder = Path(root).expanduser().resolve()
    if not folder.is_dir():
        raise ValueError(f"records directory not found: {root}")
    scan = _Scan(folder)
    _roots(scan)
    seen: set[Path] = set()
    for scope in scan.roots:
        for path in _markdown(scope):
            if path in seen:
                continue
            seen.add(path)
            _read(scan, path)
    scan.records.sort(key=lambda item: item.relative)
    return scan


def _read(scan: _Scan, path: Path) -> None:
    relative = path.relative_to(scan.folder).as_posix()
    text = path.read_text(encoding="utf-8")
    try:
        data, raw, body = split(text)
    except ValueError as exc:
        scan.fail(relative, str(exc))
        return
    # Legacy notes and other OKF types are not records; knowledge check reports them.
    if data is None or data.get("type") not in records.TYPES:
        return
    problems = records.errors(data)
    if problems:
        scan.fail(relative, "; ".join(problems))
        return
    record = records.KnowledgeRecord.model_validate(data)
    scan.records.append(_Record(path, relative, text, raw, data, body, record))


def _names(scan: _Scan) -> dict[str, list[_Record]]:
    """Every id and alias, with the records that carry it."""
    names: dict[str, list[_Record]] = defaultdict(list)
    for item in scan.records:
        own: list[str] = [item.record.id, *(item.record.aliases or [])]
        for name in sorted(set(own)):
            names[name].append(item)
    return names


# --- numbering -----------------------------------------------------------------------


def number_records(root: Path | str, *, write: bool = True) -> dict[str, Any]:
    """Number every slug-id record under ``root``; see the module docstring.

    Returns ``status`` (``numbered``, ``unchanged``, ``pending`` when ``write`` is
    false and there is work, or ``invalid``), the ``assigned`` ids with their slug,
    old and new path, the ``changed`` files and any ``failures``. Nothing is written
    when any record is invalid or a slug names more than one record.
    """
    scan = _scan(root)
    names = _names(scan)
    for name, owners in sorted(names.items()):
        if len(owners) > 1 and not NUMBERED.match(name):
            paths = ", ".join(item.relative for item in owners)
            scan.fail(owners[0].relative, f"{name} names {len(owners)} records ({paths})")
    if scan.failures:
        return _result("invalid", scan, assigned=[], changed=[])
    plan = _plan(scan, names)
    if not plan:
        return _result("unchanged", scan, assigned=[], changed=[])
    renames = {item.path: _new_path(item, number) for item, number in plan.items()}
    edits = _edits(scan, plan, renames)
    assigned = [
        {
            "id": number,
            "slug": item.record.id,
            "path": item.relative,
            "new_path": renames[item.path].relative_to(scan.folder).as_posix(),
        }
        for item, number in plan.items()
    ]
    changed = sorted(
        {path.relative_to(scan.folder).as_posix() for path in edits}
        | {path.relative_to(scan.folder).as_posix() for path in renames.values()}
    )
    if not write:
        return _result("pending", scan, assigned=assigned, changed=changed)
    for old, new in renames.items():
        if old != new:
            old.rename(new)
    for path, text in edits.items():
        renames.get(path, path).write_text(text, encoding="utf-8")
    return _result("numbered", scan, assigned=assigned, changed=changed)


def _result(status: str, scan: _Scan, **extra: Any) -> dict[str, Any]:
    failures = sorted(scan.failures, key=lambda item: (item["path"], item["message"]))
    return {"status": status, "records": len(scan.records), **extra, "failures": failures}


def _plan(scan: _Scan, names: dict[str, list[_Record]]) -> dict[_Record, str]:
    """Next number per type, in (date, path) order of the slug records."""
    highest: dict[str, int] = defaultdict(int)
    for name in names:
        match = NUMBERED.match(name)
        if match:
            prefix = name.split("-", 1)[0]
            highest[prefix] = max(highest[prefix], int(match.group(1)))
    pending = [item for item in scan.records if not NUMBERED.match(item.record.id)]
    pending.sort(key=lambda item: (item.record.date, item.relative))
    plan: dict[_Record, str] = {}
    for item in pending:
        prefix = records.PREFIXES[item.record.type]
        highest[prefix] += 1
        plan[item] = f"{prefix}-{highest[prefix]:04d}"
    return plan


def _new_path(item: _Record, number: str) -> Path:
    if item.path.stem != item.record.id:
        return item.path
    target = item.path.with_name(f"{number}.md")
    if target.exists():
        raise ValueError(f"cannot rename {item.relative}: {target.name} already exists")
    return target


def _edits(scan: _Scan, plan: dict[_Record, str], renames: dict[Path, Path]) -> dict[Path, str]:
    """New text per file (keyed by its current path); files that do not change are absent."""
    numbers = {item.record.id: number for item, number in plan.items()}
    edits: dict[Path, str] = {}
    for item in scan.records:
        number = plan.get(item)
        expected = _renumbered(item.data, numbers, number)
        front = item.raw if expected == item.data else _front(item, expected, numbers, number)
        destination = renames.get(item.path, item.path)
        body = _relink(item.body, item.path, destination, renames)
        text = item.text.replace(item.raw, front, 1) if front != item.raw else item.text
        if body != item.body:
            text = text[: len(text) - len(item.body)] + body
        if text != item.text:
            edits[item.path] = text
    for path, new in renames.items():
        if path != new and path not in edits:
            edits[path] = path.read_text(encoding="utf-8")
    return edits


def _renumbered(data: dict, numbers: dict[str, str], number: str | None) -> dict:
    """The frontmatter mapping after numbering, built from parsed data."""
    result = dict(data)
    if number is not None:
        result["id"] = number
        aliases = list(data.get("aliases") or [])
        if data["id"] not in aliases:
            aliases.append(data["id"])
        result["aliases"] = aliases
    links = []
    for link in data.get("links") or []:
        target = link.get("target")
        links.append({**link, "target": numbers.get(target, target)})
    result["links"] = links
    sources = []
    for entry in data.get("sources") or []:
        moved = dict(entry)
        for key in ("id", "resource"):
            if moved.get(key) in numbers:
                moved[key] = numbers[moved[key]]
        sources.append(moved)
    result["sources"] = sources
    return result


def _front(item: _Record, expected: dict, numbers: dict[str, str], number: str | None) -> str:
    """Edit the raw frontmatter in place; re-serialize only if the edit cannot be shown exact."""
    raw = item.raw
    for slug, new in numbers.items():
        token = re.escape(slug)
        nested = rf"((?:target|resource|id):[ \t]*)(['\"]?){token}\2(?=[ \t]*(?:[,}}\]#]|$))"
        raw = re.sub(nested, rf"\g<1>\g<2>{new}\g<2>", raw, flags=re.MULTILINE)
    if number is not None:
        raw = _alias(raw, item.record.id)
    try:
        if yaml.safe_load(raw) == expected:
            return raw
    except yaml.YAMLError:
        pass
    dumped = yaml.safe_dump(expected, sort_keys=False, default_flow_style=False, allow_unicode=True)
    return dumped.rstrip("\n")


def _alias(raw: str, slug: str) -> str:
    """Add the slug to a one-line ``aliases`` list, or add one after ``id``."""
    flow = re.compile(r"^aliases:[ \t]*\[(.*)\][ \t]*$", re.MULTILINE)
    match = flow.search(raw)
    if match:
        items = [part.strip() for part in match.group(1).split(",") if part.strip()]
        joined = ", ".join([*items, slug])
        return raw[: match.start()] + f"aliases: [{joined}]" + raw[match.end() :]
    if re.search(r"^aliases:", raw, re.MULTILINE):
        return raw  # block list: left to the verified re-serialization
    line = re.compile(r"^(id:[^\n]*)$", re.MULTILINE)
    return line.sub(lambda m: f"{m.group(1)}\naliases: [{slug}]", raw, count=1)


def _relink(body: str, source: Path, destination: Path, renames: dict[Path, Path]) -> str:
    """Rewrite relative markdown links that point at a renamed record file.

    Renames stay in one directory, so links out of a renamed file keep working.
    """
    moved = {old: new for old, new in renames.items() if old != new}
    if not moved:
        return body

    def replace(match: re.Match[str]) -> str:
        target = match.group(2)
        if ":" in target or target.startswith("/"):
            return match.group(0)
        resolved = Path(os.path.normpath(source.parent / target))
        if resolved not in moved:
            return match.group(0)
        relative = PurePosixPath(os.path.relpath(moved[resolved], destination.parent)).as_posix()
        return f"{match.group(1)}{relative}{match.group(3) or ''}{match.group(4)}"

    return MARKDOWN_LINK.sub(replace, body)


# --- indexes -------------------------------------------------------------------------


def index_records(root: Path | str, *, write: bool = True) -> dict[str, Any]:
    """Write one OKF v0.2 ``index.md`` per records directory; see the module docstring.

    Returns ``status`` (``written``, ``unchanged``, ``stale`` when ``write`` is false
    and an index differs, or ``invalid``), the ``indexes`` it owns, the ``changed``
    ones, ``superseded_by`` and ``retracted_by`` per record id and any ``failures``.
    Invalid records stop
    it before any write.
    """
    scan = _scan(root)
    if scan.failures:
        return _result("invalid", scan, indexes=[], changed=[], superseded_by={}, retracted_by={})
    successors = superseded_by(scan)
    retractions = records.retracted_by(item.record for item in scan.records)
    pages = _pages(scan, successors, retractions)
    changed = []
    for directory, text in pages.items():
        path = directory / INDEX
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            changed.append(path.relative_to(scan.folder).as_posix())
            if write:
                path.write_text(text, encoding="utf-8")
    indexes = sorted((d / INDEX).relative_to(scan.folder).as_posix() for d in pages)
    status = "unchanged" if not changed else "written" if write else "stale"
    return _result(
        status,
        scan,
        indexes=indexes,
        changed=sorted(changed),
        superseded_by=successors,
        retracted_by=retractions,
    )


def superseded_by(scan: _Scan) -> dict[str, list[str]]:
    """For each superseded record id, the ids of records whose supersedes link names it."""
    names = _names(scan)
    found: dict[str, set[str]] = defaultdict(set)
    for item in scan.records:
        for link in item.record.links:
            if link.type != "supersedes":
                continue
            for target in names.get(link.target, []):
                if target is not item:
                    found[target.record.id].add(item.record.id)
    return {name: sorted(ids) for name, ids in sorted(found.items())}


def _pages(
    scan: _Scan, successors: dict[str, list[str]], retractions: dict[str, list[str]]
) -> dict[Path, str]:
    by_directory: dict[Path, list[_Record]] = defaultdict(list)
    for item in scan.records:
        by_directory[item.path.parent].append(item)
    directories = {scan.folder}
    for directory in by_directory:
        while directory != scan.folder and directory not in directories:
            directories.add(directory)
            directory = directory.parent
    children: dict[Path, list[Path]] = defaultdict(list)
    for directory in directories:
        if directory != scan.folder:
            children[directory.parent].append(directory)
    # A customer project's tree is listed only from inside it (KAN-465).
    customer = {
        scan.folder / "projects" / name
        for item in scan.records
        if is_customer(item.record) and (name := project_of(item.relative))
    }
    pages = {}
    for directory in sorted(directories):
        view = project_of(f"{directory.relative_to(scan.folder).as_posix()}/{INDEX}")
        visible = [item for item in scan.records if visible_in(item.record, item.relative, view)]
        listed = {id(item) for item in visible}
        totals: dict[Path, int] = defaultdict(int)
        for item in visible:
            for ancestor in item.path.parents:
                totals[ancestor] += 1
                if ancestor == scan.folder:
                    break
        shown = [
            child
            for child in sorted(children[directory])
            if totals[child]
            and (child not in customer or project_of(f"{_rel(scan, child)}/x") == view)
        ]
        pages[directory] = _page(
            scan.folder,
            directory,
            shown,
            [item for item in by_directory.get(directory, []) if id(item) in listed],
            totals,
            successors,
            retractions,
        )
    return pages


def _rel(scan: _Scan, directory: Path) -> str:
    return directory.relative_to(scan.folder).as_posix()


def _page(
    folder: Path,
    directory: Path,
    subdirectories: list[Path],
    items: list[_Record],
    totals: dict[Path, int],
    successors: dict[str, list[str]],
    retractions: dict[str, list[str]],
) -> str:
    lines: list[str] = []
    if directory == folder:
        lines += ["---", f'okf_version: "{OKF_VERSION}"', "---"]
        title = "Knowledge records"
    else:
        title = directory.name.replace("-", " ").replace("_", " ").capitalize()
    lines += [f"# {title}", "", GENERATED]
    if subdirectories:
        lines += ["", "## Directories", ""]
        for child in subdirectories:
            count = totals[child]
            noun = "record" if count == 1 else "records"
            lines.append(f"* [{child.name}/]({child.name}/) - {count} {noun}")
    status = {id(item): records.effective_status(item.record, retractions) for item in items}
    active = [item for item in items if status[id(item)] not in INACTIVE]
    inactive = [item for item in items if status[id(item)] in INACTIVE]
    for kind in records.TYPES:
        group = [item for item in active if item.record.type == kind]
        if group:
            lines += ["", f"## {HEADINGS[kind]}", ""]
            lines += [_entry(item, successors, retractions) for item in _ordered(group)]
    if inactive:
        retracted = any(status[id(item)] == records.RETRACTED for item in inactive)
        heading = "Superseded, retracted and rejected" if retracted else "Superseded and rejected"
        lines += ["", f"## {heading}", ""]
        lines += [_entry(item, successors, retractions) for item in _ordered(inactive)]
    return "\n".join(lines) + "\n"


def _ordered(items: list[_Record]) -> list[_Record]:
    return sorted(items, key=lambda item: (item.record.id, item.relative))


def _entry(
    item: _Record, successors: dict[str, list[str]], retractions: dict[str, list[str]]
) -> str:
    record = item.record
    facts = [record.id, record.type, records.effective_status(record, retractions)]
    if record.id in successors:
        facts.append("superseded_by: " + ", ".join(successors[record.id]))
    if record.id in retractions:
        facts.append("retracted_by: " + ", ".join(retractions[record.id]))
    if record.tags:
        facts.append("tags: " + ", ".join(record.tags))
    if record.stale_after:
        facts.append(f"stale_after: {record.stale_after.date().isoformat()}")
    summary = _one_line(record.description) if record.description else ""
    detail = f"{summary} ({'; '.join(facts)})" if summary else f"({'; '.join(facts)})"
    return f"* [{_escape(_title(item))}]({item.path.name}) - {detail}"


def _title(item: _Record) -> str:
    if item.record.title:
        return _one_line(item.record.title)
    for line in item.body.splitlines():
        if line.startswith("# "):
            return _one_line(line[2:])
    return item.record.id


def _one_line(text: str) -> str:
    return " ".join(text.split())


def _escape(text: str) -> str:
    return text.replace("[", r"\[").replace("]", r"\]")
